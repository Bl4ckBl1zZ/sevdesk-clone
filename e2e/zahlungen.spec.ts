test("BNK-041 BNK-046 PAY-010 a statement row naming the invoice number is suggested, confirmed and pays the invoice", async ({
  page,
  expectNoAxeViolations,
}, testInfo) => {
  const { number, url } = await finalisedInvoice(page);
  const file = testInfo.outputPath("zahlung.camt053.xml");
  writeFileSync(
    file,
    camtWith({
      date: todayBerlin(),
      amount: "119.00",
      purpose: `RE ${number} Danke`,
      ref: `e2e-${testInfo.project.name}-${Date.now()}`,
    }),
  );

  await page.goto("/bank");
  await expect(h1(page, "Bank")).toBeVisible();
  await page.getByRole("button", { name: "Kontoauszug importieren" }).click();
  const dialog = page.getByRole("dialog").filter({ hasText: "Kontoauszug importieren" });
  await dialog.getByLabel("Konto", { exact: true }).selectOption({ label: "Revolut EUR (EUR)" });
  await dialog.getByLabel("Kontoauszugsdatei").setInputFiles(file);
  await dialog.getByRole("button", { name: "Vorschau" }).click();
  await expect(dialog.getByTestId("import-counts")).toContainText("1 neu", { timeout: 30_000 });
  await dialog
    .getByRole("button", { name: /importieren/i })
    .last()
    .click();
  await expect(dialog).toBeHidden({ timeout: 30_000 });

  await page.goto("/bank/zuordnungen");
  const card = page.getByTestId("match-card").filter({ hasText: number });
  await expect(card).toBeVisible({ timeout: 30_000 });
  await expect(card).toContainText("Rechnungsnr. im Verwendungszweck");
  await expectNoAxeViolations();
  await card.getByRole("button", { name: "Bestätigen" }).click();
  await expect(page.getByText("Zahlung gebucht.")).toBeVisible({ timeout: 20_000 });
  await expect(card).toBeHidden({ timeout: 20_000 });

  await page.goto(url);
  await expect(page.getByTestId("open-amount")).toHaveText("0,00 €", { timeout: 20_000 });
  await expect(page.getByTestId("payment-history")).toContainText("Bank");
  await expectNoAxeViolations();
});

test("PAY-012 PAY-040 PAY-020 partial payment, its Storno, then payment with 2 % Skonto settles the invoice", async ({
  page,
  expectNoAxeViolations,
}) => {
  const { number } = await finalisedInvoice(page, { skonto: true });

  let dialog = await openPaymentDialog(page, number);
  await dialog.getByText("Andere", { exact: true }).click();
  await dialog.getByLabel("Betrag (€)").fill("50,00");
  await expect(dialog.getByText("Teilzahlung – Rest bleibt offen")).toBeVisible();
  await expectNoAxeViolations();
  await bookButton(dialog).click();
  await expect(dialog).toBeHidden({ timeout: 20_000 });
  await expect(page.getByTestId("open-amount")).toHaveText("69,00 €", { timeout: 20_000 });

  await page.getByTestId("payment-history").getByRole("button", { name: "Stornieren" }).click();
  const reverse = page.getByRole("dialog", { name: "Zahlung stornieren" });
  await reverse.getByLabel("Grund (mindestens 5 Zeichen)").fill("Falscher Betrag erfasst");
  await reverse.getByRole("button", { name: "Stornieren" }).click();
  await expect(reverse).toBeHidden({ timeout: 20_000 });
  await expect(page.getByTestId("open-amount")).toHaveText("119,00 €", { timeout: 20_000 });
  await expect(page.getByTestId("payment-history")).toContainText("storniert");

  dialog = await openPaymentDialog(page, number);
  await dialog.getByText("Andere", { exact: true }).click();
  await dialog.getByLabel("Betrag (€)").fill("116,62");
  await dialog.getByText(/^Skonto \(2 % bis/).click();
  await expect(dialog.getByTestId("booking-preview")).toBeVisible({ timeout: 20_000 });
  await bookButton(dialog).click();
  await expect(dialog).toBeHidden({ timeout: 20_000 });
  await expect(page.getByTestId("open-amount")).toHaveText("0,00 €", { timeout: 20_000 });
  await expect(page.getByTestId("payment-history")).toContainText("Skonto 2,38 €");
});

test("PAY-061 PAY-063 CSH-021 „Bar bezahlt“ settles the invoice and archives the Quittung", async ({
  page,
  expectNoAxeViolations,
}) => {
  const { number } = await finalisedInvoice(page);
  const dialog = await openPaymentDialog(page, number);
  await dialog.getByText("Bar", { exact: true }).click();
  await dialog.getByLabel("Betrag (€)").fill("119,00");
  await expectNoAxeViolations();
  await bookButton(dialog).click();
  await expect(dialog).toBeHidden({ timeout: 20_000 });
  await expect(page.getByTestId("open-amount")).toHaveText("0,00 €", { timeout: 20_000 });
  await expect(page.getByText("Barzahlung gebucht.")).toBeVisible();

  await page.getByRole("status").getByRole("button", { name: "Quittung drucken" }).click();
  await expect(page.getByText("Quittung erstellt.")).toBeVisible({ timeout: 30_000 });
  // The first print is archived; every further print is a „Kopie“ (EC-PAY-51).
  await expect(
    page.getByTestId("payment-history").getByRole("button", { name: "Quittung drucken (Kopie)" }),
  ).toBeVisible({ timeout: 20_000 });
});

