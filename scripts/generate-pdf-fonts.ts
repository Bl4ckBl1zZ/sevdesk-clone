/**
 * Writes src/pdf/fonts/data.generated.ts (base64 TTFs) from a directory with the pinned font files.
 *
 *   pnpm tsx scripts/generate-pdf-fonts.ts <dir-with-ttf-files>
 *
 * PDF/A-3b needs embedded fonts (ADR-006, 02 §2: Inter, Noto Sans fallback; F01 SET-071 font choice). The fonts are
 * shipped as a TS module so the renderer works in every runtime (Node, Next route handlers, Convex Node actions)
 * without file-system access. Sources (all SIL OFL 1.1, licences next to the module):
 *   Inter 4.1         https://github.com/rsms/inter/releases/download/v4.1/Inter-4.1.zip (extras/ttf/)
 *   Noto Sans         https://github.com/notofonts/notofonts.github.io/raw/main/fonts/NotoSans/hinted/ttf/
 *   Source Serif 4    https://github.com/adobe-fonts/source-serif/releases/download/4.005R/source-serif-4.005_Desktop.zip (TTF/)
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export const FONT_FILES = {
  "Inter-Regular.ttf": "40d692fce188e4471e2b3cba937be967878f631ad3ebbbdcd587687c7ebe0c82",
  "Inter-Bold.ttf": "288316099b1e0a47a4716d159098005eef7c0066921f34e3200393dbdb01947f",
  "Inter-Italic.ttf": "bbc051dd204b5019a1aa0bc0ae2aa8a05ab13e7a3f979fa357631dc7feb6833a",
  "NotoSans-Regular.ttf": "478c558ea716033cd60c03438f628dfa75694dcf6b5f6d505a2f05fd2b4f3823",
  "NotoSans-Bold.ttf": "1df075a380fc7cb898acf64c1f7b3b4dd780de3caa860178bf929de35817a913",
  "SourceSerif4-Regular.ttf": "e5a4ee6a3d87bb9024796be390c6771e2a0eb1883dae25effaf57ca01668e24b",
  "SourceSerif4-Bold.ttf": "7cf4f4e1ad74f45058d5bc61716b82560442fbdcd9d3654d2dea96bf6c683d86",
} as const;

function main(dir: string) {
  const entries = Object.entries(FONT_FILES).map(([name, sha]) => {
    const bytes = readFileSync(join(dir, name));
    const actual = createHash("sha256").update(bytes).digest("hex");
    if (actual !== sha) throw new Error(`${name}: sha256 ${actual} ≠ pinned ${sha}`);
    return `  "${name}": { sha256: "${sha}", base64: "${bytes.toString("base64")}" },`;
  });
  const out = [
    "// GENERATED by scripts/generate-pdf-fonts.ts — do not edit. Fonts: SIL OFL 1.1 (see LICENSE-*.txt/md).",
    "export const FONT_DATA = {",
    ...entries,
    "} as const;",
    "",
  ].join("\n");
  const target = join(import.meta.dirname, "..", "src", "pdf", "fonts", "data.generated.ts");
  writeFileSync(target, out);
  console.info(`wrote ${target} (${Math.round(out.length / 1024)} KiB)`);
}

const dir = process.argv[2];
if (dir) main(dir);
