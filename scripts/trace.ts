/**
 * Requirement ↔ test traceability (07-testing §6). Minimal working version.
 *
 *   pnpm trace                    # print coverage per spec file + per phase
 *   pnpm trace --phase P1 --gate  # exit 1 if a MUST requirement with phase ≤ P1 has no test, or a test names an unknown ID
 *   pnpm trace --write            # also write docs/traceability.md
 *   pnpm trace --missing          # list untested requirements (respects --phase)
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { buildCoverage } from "./trace/coverage";
import { mergeRegistry, parseSpec, type Requirement } from "./trace/parse-spec";
import { scanTests, type TestRef } from "./trace/scan-tests";

const ROOT = join(import.meta.dirname, "..");
const args = process.argv.slice(2);
const flag = (name: string) => args.includes(name);
const phaseArg = args[args.indexOf("--phase") + 1];
const targetPhase = args.includes("--phase") && phaseArg ? Number(phaseArg.replace(/^P/i, "")) : null;

const SKIP_DIRS = new Set([
  "node_modules",
  ".next",
  ".git",
  "coverage",
  "playwright-report",
  "test-results",
  "_generated",
]);

function walk(dir: string, match: (p: string) => boolean, acc: string[] = []): string[] {
  for (const name of readdirSync(dir)) {
    if (SKIP_DIRS.has(name)) continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, match, acc);
    else if (match(p)) acc.push(p);
  }
  return acc;
}

const specFiles = [
  join(ROOT, "docs/spec/01-compliance.md"),
  join(ROOT, "docs/spec/10-edge-cases.md"),
  join(ROOT, "docs/spec/05-api.md"),
  join(ROOT, "docs/spec/06-mcp.md"),
  ...walk(join(ROOT, "docs/spec/features"), (p) => p.endsWith(".md")).sort(),
];
const registry = mergeRegistry(specFiles.map((f) => parseSpec(relative(ROOT, f), readFileSync(f, "utf8"))));

const testFiles = ["src", "convex", "test", "e2e", "scripts", "deploy", "services"].flatMap((d) =>
  // scripts/trace/** is excluded: its own tests contain example titles as fixtures.
  walk(join(ROOT, d), (p) => /\.(test|spec)\.tsx?$/.test(p) && !p.includes(join("scripts", "trace"))),
);
const refs: TestRef[] = testFiles.flatMap((f) => scanTests(relative(ROOT, f), readFileSync(f, "utf8")));

// Test-case IDs (T-SET-005, TST-AUD-07, T05-001) and edge cases (E-AUD-17) are spec rows too; a test-case ID also
// counts for the requirements its row covers. EN 16931 terms (BT-81) are annotations; anything else is unknown.
const { testsById, unknown } = buildCoverage(registry, refs);
const requirements = [...registry.values()].filter((r) => r.kind !== "test-case");
const testCaseCount = registry.size - requirements.length;

const inScope = (r: Requirement) => targetPhase === null || (r.phase !== null && r.phase <= targetPhase);
const gated = (r: Requirement) => r.priority === "MUST" && r.phase !== null && inScope(r);

// ── report ────────────────────────────────────────────────────────────────────
type Row = { group: string; total: number; tested: number };
const byFile = new Map<string, Row>();
for (const r of requirements) {
  if (!inScope(r) && targetPhase !== null) continue;
  const row = byFile.get(r.file) ?? { group: r.file, total: 0, tested: 0 };
  row.total++;
  if (testsById.has(r.id)) row.tested++;
  byFile.set(r.file, row);
}
const pct = (a: number, b: number) => (b === 0 ? "–" : `${Math.round((a / b) * 100)} %`);
const lines: string[] = [];
lines.push(`| Spec file | Requirements | Tested | Coverage |`, `|---|---:|---:|---:|`);
let total = 0;
let tested = 0;
for (const row of [...byFile.values()].sort((a, b) => a.group.localeCompare(b.group))) {
  lines.push(`| ${row.group} | ${row.total} | ${row.tested} | ${pct(row.tested, row.total)} |`);
  total += row.total;
  tested += row.tested;
}
lines.push(`| **Total** | **${total}** | **${tested}** | **${pct(tested, total)}** |`);

const phaseLines: string[] = [`| Phase | MUST | MUST tested |`, `|---|---:|---:|`];
for (let p = 0; p <= 4; p++) {
  const must = [...registry.values()].filter((r) => r.priority === "MUST" && r.phase === p);
  phaseLines.push(`| P${p} | ${must.length} | ${must.filter((r) => testsById.has(r.id)).length} |`);
}

const missing = [...registry.values()].filter((r) => gated(r) && !testsById.has(r.id));

console.log(`Traceability${targetPhase !== null ? ` (phase ≤ P${targetPhase})` : ""}`);
console.log(
  `${requirements.length} requirement/edge-case IDs and ${testCaseCount} test cases in spec, ${refs.length} ID references in ${testFiles.length} test files\n`,
);
console.log(lines.join("\n"));
console.log(`\n${phaseLines.join("\n")}\n`);
if (flag("--missing")) for (const r of missing) console.log(`  missing  ${r.id.padEnd(12)} P${r.phase}  ${r.title}`);
if (unknown.length) console.log(`Unknown IDs referenced by tests: ${unknown.join(", ")}`);

if (flag("--write")) {
  const md = [
    "# Traceability matrix",
    "",
    "> Generated by `pnpm trace --write` (07-testing §6). Do not edit by hand.",
    "",
    lines.join("\n"),
    "",
    phaseLines.join("\n"),
    "",
    "| Requirement | Priority | Phase | Tests |",
    "|---|---|---|---|",
    ...requirements.map(
      (r) =>
        `| ${r.id} | ${r.priority} | ${r.phase === null ? "–" : `P${r.phase}`} | ${(testsById.get(r.id) ?? []).map((t) => `\`${t.file}\``).join("<br>") || "—"} |`,
    ),
    "",
  ].join("\n");
  writeFileSync(join(ROOT, "docs/traceability.md"), md);
  console.log("wrote docs/traceability.md");
}

if (flag("--gate")) {
  if (targetPhase === null) {
    console.error("--gate needs --phase Pn");
    process.exit(2);
  }
  if (missing.length || unknown.length) {
    console.error(`\nGate failed: ${missing.length} untested MUST requirement(s), ${unknown.length} unknown ID(s).`);
    process.exit(1);
  }
  console.log("Gate passed.");
}
