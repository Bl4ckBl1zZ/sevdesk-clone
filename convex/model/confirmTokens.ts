import { ALL_PERMISSIONS, canKeyDo, confirmIntentFor, type Permission } from "../../src/domain/access/permissions";
import {
  CONFIRM_TOKEN_TTL_MS,
  type ConfirmIntent,
  checkConfirmToken,
  confirmParamsHash,
  type EntityVersion,
  isConfirmIntent,
} from "../../src/domain/api/confirm";
import { sha256Hex } from "../../src/domain/audit/chain";
import { parseActor } from "../../src/domain/schemas/actor";
import type { TableNames } from "../_generated/dataModel";
import { appError } from "../lib/errors";
import type { ModelCtx, ReadCtx } from "./types";

/**
 * Confirm tokens for ⚠ MCP tools (06 §2.3, EC-003, EC-188). Technical table `confirmTokens` (only the SHA-256 of
 * the token is stored). Issued by the preview tools for an intent; consumed by the mutation wrapper
 * (convex/functions.ts) in the transaction of the guarded act.
 */

/** The permission an intent guards (the one whose rule names it in `confirm`). */
export function permissionForIntent(intent: ConfirmIntent): Permission | undefined {
  return ALL_PERMISSIONS.find((p) => confirmIntentFor(p) === intent);
}

function callerKeyId(ctx: { actor: string }): string {
  const { kind, id } = parseActor(ctx.actor);
  if (kind !== "mcp") throw appError("forbidden_scope", "Bestätigungs-Token gibt es nur für MCP-Schlüssel.");
  return id;
}

async function entityVersion(ctx: ReadCtx, table: string, id: string): Promise<number | null | undefined> {
  const normalized = ctx.db.normalizeId(table as TableNames, id);
  if (!normalized) return undefined;
  const doc = (await ctx.db.get(normalized)) as { version?: unknown } | null;
  if (!doc) return undefined;
  return typeof doc.version === "number" ? doc.version : null;
}

export interface IssueInput {
  intent: string;
  /** Arguments of the guarded Convex mutation exactly as the ⚠ tool will send them (without confirmToken). */
  args: Record<string, unknown>;
  /** Records whose current version the token binds (EC-003). */
  entities: { table: string; id: string }[];
  /** SHA-256 of the token generated by `web` (the plaintext never reaches Convex). */
  tokenHash: string;
}

export async function issueConfirmToken(ctx: ModelCtx, input: IssueInput): Promise<{ expiresAt: number }> {
  const keyId = callerKeyId(ctx);
  if (!isConfirmIntent(input.intent)) {
    throw appError("invalid_input", `Unbekannte Aktion ${input.intent}.`, {
      reason: "UNKNOWN_ACTION",
      field: "action",
    });
  }
  const permission = permissionForIntent(input.intent);
  if (!permission) {
    throw appError("invalid_input", `Die Aktion ${input.intent} ist noch nicht verfügbar.`, {
      reason: "ACTION_NOT_AVAILABLE",
      field: "action",
    });
  }
  // 06 §3.1 preview_action: the scope of the previewed tool.
  if (!canKeyDo(ctx.actorContext.scopes ?? [], permission)) {
    throw appError("forbidden_scope", undefined, { permission });
  }
  if (!/^[0-9a-f]{64}$/.test(input.tokenHash)) throw appError("invalid_input", "Ungültiger Token-Hash.");
  const entities: EntityVersion[] = [];
  for (const e of input.entities) {
    const version = await entityVersion(ctx, e.table, e.id);
    if (version === undefined) throw appError("not_found", `${e.table}/${e.id} nicht gefunden.`);
    entities.push({ table: e.table, id: e.id, version });
  }
  const now = ctx.now();
  const expiresAt = now + CONFIRM_TOKEN_TTL_MS;
  await ctx.db.insert("confirmTokens", {
    tokenHash: input.tokenHash,
    apiKeyId: keyId,
    intent: input.intent,
    paramsHash: await confirmParamsHash(input.args),
    entities,
    expiresAt,
    createdAt: now,
  });
  return { expiresAt };
}

/** Called by the mutation wrapper for `mcp:` actors before a ⚠ act; throws the 06 §2.3 error codes. */
export async function consumeConfirmToken(
  ctx: ModelCtx,
  intent: ConfirmIntent,
  token: string | undefined,
  args: Record<string, unknown>,
): Promise<void> {
  if (!token) throw appError("confirm_token_required");
  const keyId = callerKeyId(ctx);
  const tokenHash = await sha256Hex(token);
  const row = await ctx.db
    .query("confirmTokens")
    .withIndex("by_tokenHash", (q) => q.eq("tokenHash", tokenHash))
    .unique();
  const current = new Map<string, number | null | undefined>();
  for (const e of row?.entities ?? []) current.set(`${e.table}:${e.id}`, await entityVersion(ctx, e.table, e.id));
  const error = checkConfirmToken(
    row
      ? {
          keyId: row.apiKeyId,
          intent: row.intent,
          paramsHash: row.paramsHash,
          entities: row.entities,
          expiresAt: row.expiresAt,
          ...(row.usedAt !== undefined ? { usedAt: row.usedAt } : {}),
        }
      : null,
    { keyId, intent, paramsHash: await confirmParamsHash(args), now: ctx.now(), current },
  );
  if (error) throw appError(error);
  if (row) await ctx.db.patch("confirmTokens", row._id, { usedAt: ctx.now() });
}

export async function purgeConfirmTokens(ctx: ModelCtx, now: number, max: number): Promise<number> {
  const rows = await ctx.db
    .query("confirmTokens")
    .withIndex("by_expiresAt", (q) => q.lte("expiresAt", now))
    .take(max);
  for (const r of rows) await ctx.db.delete("confirmTokens", r._id);
  return rows.length;
}
